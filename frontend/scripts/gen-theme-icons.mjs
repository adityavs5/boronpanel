// Generates the themed icon layer from src/themes/icon-table.mjs. Application
// code keeps importing from 'lucide-react'; vite.config.js points that at the
// generated proxy, which draws each icon from the active theme's set.
import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'
import { ICONS, GRID_TOOL_ICONS, GRID_TONES } from '../src/themes/icon-table.mjs'

const require = createRequire(import.meta.url)
const root = path.resolve(import.meta.dirname, '../src')
const used = new Set()
for (const file of fs.readdirSync(root, { recursive: true })) {
  if (!/\.jsx?$/.test(file) || file.includes('.gen.')) continue
  const source = fs.readFileSync(path.join(root, file), 'utf8')
  for (const match of source.matchAll(/import\s*\{([^}]*)\}\s*from\s*'lucide-react'/g)) {
    for (const part of match[1].split(',')) { const name = part.trim().split(/\s+as\s+/)[0]; if (name) used.add(name) }
  }
}
const names = [...used].sort()
const phosphor = require('react-icons/pi'), remix = require('react-icons/ri')
const problems = []
for (const name of names) {
  if (!ICONS[name]) { problems.push(`no mapping for lucide icon ${name}`); continue }
  const [pi, ri] = ICONS[name]
  if (!phosphor[`Pi${pi}Duotone`]) problems.push(`${name}: Pi${pi}Duotone does not exist`)
  if (!remix[ri]) problems.push(`${name}: ${ri} does not exist`)
}
for (const [route, [glyph, tone]] of Object.entries(GRID_TOOL_ICONS)) {
  if (!remix[glyph]) problems.push(`${route}: ${glyph} does not exist`)
  if (!GRID_TONES.includes(tone)) problems.push(`${route}: unknown tone ${tone}`)
}
if (problems.length) { console.error(problems.join('\n')); process.exit(1) }

const header = '// Generated by scripts/gen-theme-icons.mjs. Do not edit.\n'
const unique = (values) => [...new Set(values)].sort()
const write = (file, text) => fs.writeFileSync(path.join(root, file), header + text)

write('themes/lucide-proxy.gen.js', `import { themed } from './themed-icon'
import {\n${names.map(n => `  ${n} as Lucide${n},`).join('\n')}\n} from 'lucide-react/dist/esm/lucide-react.js'
${names.map(n => `export const ${n} = themed('${n}', Lucide${n})`).join('\n')}
`)
write('themes/classic/icons.gen.js', `import {\n${unique(names.map(n => `Pi${ICONS[n][0]}Duotone`)).map(n => `  ${n},`).join('\n')}\n} from 'react-icons/pi'
export default {\n${names.map(n => `  ${n}: Pi${ICONS[n][0]}Duotone,`).join('\n')}\n}
`)
write('themes/grid/icons.gen.js', `import {\n${unique([...names.map(n => ICONS[n][1]), ...Object.values(GRID_TOOL_ICONS).map(([glyph]) => glyph)]).map(n => `  ${n},`).join('\n')}\n} from 'react-icons/ri'
import { tile } from './tile'
export default {\n${names.map(n => `  ${n}: ${ICONS[n][1]},`).join('\n')}\n}
export const toolIcons = {\n${Object.entries(GRID_TOOL_ICONS).map(([route, [glyph, tone]]) => `  ${JSON.stringify(route)}: tile(${glyph}, '${tone}'),`).join('\n')}\n}
`)
console.log(`themed icons: ${names.length} icons, ${Object.keys(GRID_TOOL_ICONS).length} tool pictograms`)
